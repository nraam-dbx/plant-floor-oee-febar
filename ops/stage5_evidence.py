"""Regenerate evidence/08_genie_agents.md: Genie space, Knowledge Assistant, Supervisor + tools, and live answers to probe
questions from each (Genie conversation API, KA endpoint, Supervisor endpoint). Eval scores are in 09_agent_eval_run.ipynb."""
import datetime, json, re, subprocess

PROFILE = "fevm-nraameast1"
env = dict(re.findall(r'^([A-Z_]+)="([^"]*)"', open("config.env").read(), re.M))

def cli(*args):
    out = subprocess.run(["databricks", *args, "-p", PROFILE, "-o", "json"], capture_output=True, text=True, check=True).stdout
    return json.loads(out, strict=False)

def invoke(endpoint, question):
    d = cli("api", "post", f"/serving-endpoints/{endpoint}/invocations", "--json",
            json.dumps({"input": [{"role": "user", "content": question}]}))
    calls = [o.get("name", "").split("__")[-1] for o in d.get("output", []) if o.get("type") == "function_call"]
    texts = [c.get("text", "") for o in d.get("output", []) if o.get("type") == "message" for c in o.get("content", []) if c.get("text")]
    return calls, "".join(texts[-1:]) if endpoint.startswith("mas-") else "".join(texts)

space = cli("genie", "get-space", env["GENIE_SPACE_ID"], "--include-serialized-space")
ser = json.loads(space["serialized_space"])
ka = cli("knowledge-assistants", "get-knowledge-assistant", env["KNOWLEDGE_ASSISTANT"])
ka_src = cli("knowledge-assistants", "list-knowledge-sources", env["KNOWLEDGE_ASSISTANT"])
sa = cli("supervisor-agents", "get-supervisor-agent", env["SUPERVISOR_AGENT"])
tools = cli("supervisor-agents", "list-tools", env["SUPERVISOR_AGENT"])

out = ["# Evidence 08 — Genie space, Knowledge Assistant, Supervisor agent (live)", "",
       f"Generated {datetime.datetime.now():%Y-%m-%d %H:%M} by `ops/stage5_evidence.py`. LLM-judge evaluation: `09_agent_eval_run.ipynb`.", "",
       f"## Genie space — {space['title']} (`{env['GENIE_SPACE_ID']}`, defined in agents/03_genie_space.py)", "", "```",
       "tables:           " + ", ".join(t["identifier"].split(".")[-1] for t in ser["data_sources"]["tables"]),
       f"example SQLs:     {len(ser['instructions']['example_question_sqls'])}",
       "sample questions: " + " | ".join(q["question"][0] for q in ser["config"]["sample_questions"]), "```", ""]

q = "Which work center had the lowest average OEE, and what was its biggest loss factor?"
g = cli("genie", "start-conversation", env["GENIE_SPACE_ID"], q)
out += [f"**Probe:** {q}", "", "```"]
for a in g.get("attachments", []):
    if a.get("query"): out += ["SQL generated by Genie:", a["query"]["query"].strip(), ""]
    if a.get("text"): out += ["Answer: " + a["text"]["content"]]
out += ["```", "",
        f"## Knowledge Assistant — {ka['display_name']} (state {ka['state']}, endpoint `{ka['endpoint_name']}`)", "", "```"]
out += [f"source: {s['display_name']} ({s['source_type']}) {s.get('files', {}).get('path', '')} state={s['state']}" for s in ka_src]
q = "What is the part number for the CNC front spindle bearing set, and which procedure covers the replacement?"
out += ["```", "", f"**Probe:** {q}", "", "```", invoke(ka["endpoint_name"], q)[1].strip(), "```", "",
        f"## Supervisor agent — {sa['display_name']} (endpoint `{sa['endpoint_name']}`)", "",
        "Instructions: `agents/04_supervisor_instructions.md`. Tools:", "", "```"]
for t in tools:
    target = t.get("genie_space", {}).get("id") or t.get("uc_function", {}).get("name") or t.get("knowledge_assistant", {}).get("knowledge_assistant_id")
    out.append(f"{t['tool_id']:28s} {t['tool_type']:20s} {target}")
q = "What should I do about CNC-02 before next shift? Include the procedure and the parts to pre-stage."
calls, ans = invoke(sa["endpoint_name"], q)
out += ["```", "", f"**Probe:** {q}", "", f"Tools called, in order: `{' -> '.join(calls)}`", "", "```", ans.strip(), "```", ""]
open("evidence/08_genie_agents.md", "w").write("\n".join(out))
print("wrote evidence/08_genie_agents.md")
